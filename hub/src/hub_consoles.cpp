std::vector<std::string> ConsoleBackend::toolchain_problems(const Settings& s) const {
    std::vector<std::string> problems = s.shared_toolchain_problems();
    const std::string exe = s.recompiler(family_id());
    if (exe.empty() || !platform::exists(exe)) problems.push_back(recompiler_name() + " executable not found");
    if (requires_sdl2()) {
#ifdef _WIN32
        if (s.sdl2_dll.empty() || !platform::exists(s.sdl2_dll)) problems.push_back("SDL2.dll not found");
#endif
        if (s.sdl2_cmake_dir.empty() || !platform::is_directory(s.sdl2_cmake_dir)) problems.push_back("SDL2 CMake directory not found");
    }
    return problems;
}

// The build script every backend uses: its generate steps, then CMake and
// Ninja on the generated project, then SDL2.dll beside the executable.
bool ConsoleBackend::prepare_build(const BuildRequest& request, BuildPlan& plan, std::string& error) const {
    const Settings& s = *request.settings;
    for (const auto& problem : toolchain_problems(s)) error += (error.empty() ? "" : "; ") + problem;
    if (!error.empty()) {
        error = "toolchain not ready: " + error + ". Fix this in Settings.";
        return false;
    }

    plan.work_dir = platform::join(request.game_dir, "work");
    plan.source_dir = platform::join(plan.work_dir, "src");
    const std::string build_dir = platform::join(plan.source_dir, "build");
#ifdef _WIN32
    plan.expected_executable = platform::join(build_dir, request.game_id + ".exe");
#else
    plan.expected_executable = platform::join(build_dir, request.game_id);
#endif
    plan.script_path = platform::join(request.game_dir, "build" + platform::script_extension());

    const std::vector<GenerateStep> generate = generate_steps(s, request.rom_path, request.game_id, plan.source_dir,
                                                              platform::join(request.game_dir, "profile"));
    const std::string total = std::to_string(generate.size() + 2);
    const std::string configure_step = std::to_string(generate.size() + 1) + "/" + total;
    std::vector<std::string> configure = {s.cmake_exe, "-G", "Ninja", "-S", plan.source_dir, "-B", build_dir,
                                          "-DCMAKE_BUILD_TYPE=" + s.build_type};
    if (!s.sdl2_cmake_dir.empty()) configure.push_back("-DSDL2_DIR=" + s.sdl2_cmake_dir);
    for (auto& arg : cmake_args(s)) configure.push_back(arg);
    const std::vector<std::string> compile = {s.ninja_exe, "-C", build_dir};

    std::ostringstream script;
#ifdef _WIN32
    auto q = [](const std::string& v) { return "\"" + v + "\""; };
    auto command = [&](const std::vector<std::string>& argv) {
        std::string line;
        for (size_t i = 0; i < argv.size(); ++i) line += (i ? " " : "") + q(argv[i]);
        return line;
    };
    script << "@echo off\r\n"
           << "setlocal\r\n"
           << "rem Generated by Native Console Hub. Re-run to rebuild this game.\r\n";
    if (!s.vcvars_bat.empty()) {
        script << "call " << q(s.vcvars_bat) << " >nul\r\n"
               << "if errorlevel 1 (echo [hub] vcvars64.bat failed & exit /b 1)\r\n";
    }
    script << "set \"PATH=" << platform::parent_path(s.cmake_exe) << ";" << platform::parent_path(s.ninja_exe) << ";%PATH%\"\r\n";
    for (size_t i = 0; i < generate.size(); ++i) {
        script << "echo [hub] step " << i + 1 << "/" << total << ": " << generate[i].label << "\r\n"
               << command(generate[i].argv) << "\r\n"
               << "if errorlevel 1 exit /b 1\r\n";
    }
    script << "echo [hub] step " << configure_step << ": configuring native project\r\n"
           << command(configure) << "\r\n"
           << "if errorlevel 1 exit /b 1\r\n"
           << "echo [hub] step " << total << "/" << total << ": compiling native executable\r\n"
           << command(compile) << "\r\n"
           << "if errorlevel 1 exit /b 1\r\n";
    if (!s.sdl2_dll.empty()) {
        script << "copy /y " << q(s.sdl2_dll) << " " << q(build_dir + "\\") << " >nul\r\n";
    }
    script << "echo [hub] done: " << plan.expected_executable << "\r\n"
           << "exit /b 0\r\n";
#else
    auto q = [](const std::string& v) { return platform::quote_arg(v); };
    auto command = [&](const std::vector<std::string>& argv) {
        std::string line;
        for (size_t i = 0; i < argv.size(); ++i) line += (i ? " " : "") + q(argv[i]);
        return line;
    };
    script << "#!/bin/sh\n"
           << "# Generated by Native Console Hub. Re-run to rebuild this game.\n"
           << "set -e\n";
    for (size_t i = 0; i < generate.size(); ++i) {
        script << "echo '[hub] step " << i + 1 << "/" << total << ": " << generate[i].label << "'\n"
               << command(generate[i].argv) << "\n";
    }
    script << "echo '[hub] step " << configure_step << ": configuring native project'\n"
           << command(configure) << "\n"
           << "echo '[hub] step " << total << "/" << total << ": compiling native executable'\n"
           << command(compile) << "\n"
           << "echo '[hub] done: " << plan.expected_executable << "'\n";
#endif
    std::ofstream out(platform::to_path(plan.script_path), std::ios::binary | std::ios::trunc);
    if (!out) {
        error = "cannot write " + plan.script_path;
        return false;
    }
    out << script.str();
    return true;
}

std::vector<std::string> trace_files(const std::string& data_dir, const std::string& boot_trace) {
    std::vector<std::string> out = {boot_trace};
    if (platform::is_directory(data_dir)) {
        for (const auto& file : platform::list_files_recursive(data_dir, {".txt"})) {
            if (file != boot_trace && platform::parent_path(file) == data_dir) out.push_back(file);
        }
    }
    return out;
}

const ConsoleInfo* console_info(const std::string& console_id) {
    for (const auto& c : all_consoles()) {
        if (c.id == console_id) return &c;
    }
    return nullptr;
}

const std::vector<std::unique_ptr<ConsoleBackend>>& backends() {
    static std::vector<std::unique_ptr<ConsoleBackend>> list = [] {
        std::vector<std::unique_ptr<ConsoleBackend>> v;
        v.push_back(make_gameboy_backend());
        v.push_back(make_gba_backend());
        v.push_back(make_snes_backend());
        v.push_back(make_nes_backend());
        v.push_back(make_nds_backend());
        v.push_back(make_n64_backend());
        v.push_back(make_gc_backend());
        v.push_back(make_wii_backend());
        for (auto& b : extra_families().backends) v.push_back(std::move(b));
        return v;
    }();
    return list;
}

const ConsoleBackend* backend_for_family(const std::string& family_id) {
    for (const auto& b : backends()) {
        if (b->family_id() == family_id) return b.get();
    }
    return nullptr;
}

const ConsoleBackend* backend_for_file(const std::string& path) {
    std::string ext = platform::file_extension_lower(path);
    std::string name = platform::file_name(path);
    std::transform(name.begin(), name.end(), name.begin(), [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    // More than one family can use an extension - a GameCube disc and a Wii
    // disc are both .iso - and then the file itself says whose it is: the
    // first claimant whose probe takes it, or the first claimant when none
    // does (so the error a user sees is that family's).
    const ConsoleBackend* first = nullptr;
    std::vector<const ConsoleBackend*> claimants;
    for (const auto& b : backends()) {
        auto exts = b->extensions();
        auto names = b->file_names();
        if ((!ext.empty() && std::find(exts.begin(), exts.end(), ext) != exts.end()) ||
            std::find(names.begin(), names.end(), name) != names.end()) {
            if (!first) first = b.get();
            claimants.push_back(b.get());
        }
    }
    if (claimants.size() < 2) return first;
    for (const ConsoleBackend* b : claimants) {
        RomInfo info;
        std::string error;
        if (b->probe(path, info, error)) return b;
    }
    return first;
}

std::vector<std::string> roms_in_folder(const std::string& dir) {
    // Everything is listed rather than filtered by extension during the walk,
    // because a family whose game has no extension is matched by name.
    std::vector<std::string> out;
    for (const auto& file : platform::list_files_recursive(dir, {})) {
        if (backend_for_file(file)) out.push_back(file);
    }
    return out;
}

std::string sanitize_header_title(const std::string& raw) {
    std::string out;
    for (unsigned char c : raw) {
        if (c == 0) break;
        if (c >= 0x20 && c < 0x7F) out.push_back(static_cast<char>(c));
    }
    while (!out.empty() && out.back() == ' ') out.pop_back();
    while (!out.empty() && out.front() == ' ') out.erase(out.begin());
    return out;
}

std::string title_from_file_name(const std::string& path) {
    std::string stem = platform::file_stem(path);
    // Strip trailing dump tags such as "(USA, Europe) (Rev 2)" or "[!]" from No-Intro style names.
    while (true) {
        size_t open = stem.find_last_of("([");
        if (open == std::string::npos) break;
        char close = stem[open] == '(' ? ')' : ']';
        if (stem.find(close, open) == std::string::npos) break;
        if (stem.find_first_not_of(" ", stem.find(close, open) + 1) != std::string::npos) break;
        stem.erase(open);
        while (!stem.empty() && stem.back() == ' ') stem.pop_back();
    }
    // "Legend of Zelda, The - Link's Awakening" -> "The Legend of Zelda - Link's Awakening"
    size_t comma = stem.find(", The");
    if (comma != std::string::npos && (comma + 5 == stem.size() || stem.compare(comma + 5, 3, " - ") == 0 || stem[comma + 5] == ':')) {
        stem = "The " + stem.substr(0, comma) + stem.substr(comma + 5);
    }
    for (char& c : stem) {
        if (c == '_') c = ' ';
    }
    return stem.empty() ? platform::file_stem(path) : stem;
}

