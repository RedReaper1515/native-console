import gb_discover  # noqa: E402  (the layout of a save state)

START = 0x0150
# A `ret` at each of these, and three bytes of code at 4800: the data between two of them is a region.
CODE = {0x2000: [0xC9], 0x3000: [0xC9], 0x4800: [0x3E, 0x01, 0xC9], 0x5000: [0xC9], 0x6000: [0xC9], 0x7000: [0xC9]}
HOME, PACKS, ODDS, TILES, TWIN1, TWIN2, SEEN, LAST = 0x0153, 0x2001, 0x3001, 0x4000, 0x4803, 0x5001, 0x6001, 0x7001
STRING0, FONT, STRING1, SHOUT, STRING2, SPARE = 0x0180, 0x0200, 0x0300, 0x0340, 0x0341, 0x0400
SPRITE, WALK, BARE, MUGSHOT = 0x4100, 0x4180, 0x4200, 0x4300
UNPACK, BUFFER = 0x2000, 0xC100
# The streams, each as a game gives it: the bank its register held, and its address.
HERO, PACKED, PLAIN, LATE = (1, 0x2100), (1, 0x4801), (0, 0x2200), (1, 0x2300)
LINE, END, SPACE = 0x4F, 0x50, 0x7F
SYMBOLS = """\
; File generated by rgblink
00:0100 Start
00:0200 Font
00:0300 Greeting
00:0340 Shout
00:2000 Unpack
00:2100 Hero
00:2300 Late
00:c100 wBuffer
01:4000 Tiles
01:4100 Sprite
01:4180 Sprite.frame2
01:4180 Walk
01:4300 TilesEnd
01:4300 Mugshot
01:4800 Routine
01:4801 Packed
01:4803 Twin
01:5001 TWIN
7f:4000 Nowhere
"""
BROUGHT_IN = """\
00:0200 Font ; from game.sym
00:0300 Greeting ; from game.sym
00:0340 Shout ; from game.sym
00:2100 Hero ; from game.sym
00:2300 Late ; from game.sym
01:4000 Tiles ; from game.sym
01:4100 Sprite ; from game.sym
01:4180 Walk ; from game.sym
01:4180 Sprite.frame2 ; from game.sym
01:4300 Mugshot ; from game.sym
01:4300 TilesEnd ; from game.sym
01:4801 Packed ; from game.sym
01:4803 Twin ; from game.sym
01:5001 TWIN ; from game.sym
"""
DECLARATION = {"schema": "gbrecomp.unpackers", "version": 1, "unpackers": [
    {"name": "tiles", "function": {"bank": 0, "address": UNPACK},
     "stream": {"bank": {"register": "a"}, "address": {"register": "hl"}},
     "made": [{"address": BUFFER, "size": 16}], "as": {"kind": "tiles", "bpp": 2, "width": 16}}]}
# What the routine makes of each stream. Every bit of a byte goes its own way through the first
# and the third, so the tool can tell that a second way of unpacking them changes the halves about.
MADE = {HERO: bytes([0x55] * 4 + [0x66] * 4 + [0x78] * 4 + [0x80] * 4),
        PACKED: bytes([0xF0] * 8 + [0x0F] * 8),
        PLAIN: bytes([0x80] * 4 + [0x78] * 4 + [0x66] * 4 + [0x55] * 4),
        LATE: bytes([0x66, 0x99] * 8)}        # the same both ways


def letters_of(text: str) -> bytes:
    """A to P are the bytes 80 to 8F."""
    return bytes(SPACE if letter == " " else 0x80 + ord(letter) - ord("A") for letter in text)


TEXT0 = letters_of("FEED") + bytes([END])
TEXT1 = letters_of("BAD CAFE") + bytes([LINE]) + letters_of("A FAB BEAD") + bytes([END])
TEXT2 = letters_of("DEAF CAB") + bytes([END])
CHARMAP = {"schema": "gbrecomp.charmap", "version": 1,
           "letters": dict({f"{0x80 + index:02X}": chr(ord("A") + index) for index in range(16)},
                           **{f"{SPACE:02X}": " ", f"{LINE:02X}": "{line}", f"{END:02X}": "{end}"})}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def halves_changed(data: bytes) -> bytes:
    return bytes(((value << 4) | (value >> 4)) & 0xFF for value in data)


def make_rom() -> bytearray:
    noise = random.Random(1996)
    rom = bytearray(noise.randbytes(0x8000))
    rom[0:0x150] = bytes(0x150)
    rom[0x100:0x104] = bytes([0x00, 0xC3, START & 0xFF, START >> 8])
    rom[0x104:0x134] = NINTENDO_LOGO
    rom[0x134:0x13E] = b"DATA NAMES"
    rom[0x14D] = (-sum(rom[0x134:0x14D]) - 25) & 0xFF
    rom[START:START + 3] = bytes([0xF3, 0x18, 0xFE])                  # di / jr to itself
    for address, code in CODE.items():
        rom[address:address + len(code)] = bytes(code)
    for address, text in ((STRING0, TEXT0), (STRING1, TEXT1), (STRING2, TEXT2)):
        rom[address:address + len(text)] = text
    return rom


def use_record(rom: bytes) -> dict:
    """What a game run with --data-use would have written: one instruction read the three
    strings and put their letters on the screen, another drew tiles from three regions, and
    one of those regions it mostly read addresses from."""
    def run(address: int, size: int, uses: list[str], reader: int) -> dict:
        return {"offset": address, "size": size, "bank": address // 0x4000, "address": address,
                "as_it_is": uses, "worked_out": [], "read_at": [0, reader], "one_reader": True}

    ranges = []
    for address, text in ((STRING0, TEXT0), (STRING1, TEXT1), (STRING2, TEXT2)):
        ranges += [run(address + index, 1, [] if byte in (LINE, END) else ["tile_map"], 0x0151)
                   for index, byte in enumerate(text)]
    ranges += [run(TILES, 256, ["tiles"], 0x0152), run(SEEN + 15, 32, ["tiles"], 0x0152),
               run(ODDS + 4, 2, ["tiles"], 0x0152), run(ODDS + 16, 6, ["pointer"], 0x0100)]
    return {"schema": "gbrt.data-use", "version": 1,
            "rom": {"size": len(rom), "global_checksum": (rom[0x14E] << 8) | rom[0x14F]},
            "instructions": 1000, "ranges": sorted(ranges, key=lambda entry: entry["offset"])}


def harvest(rom: bytes, things: list[tuple[tuple[int, int], bytes]]) -> dict:
    """What a game run with --unpacked-harvest would have written."""
    return {"schema": "gbrt.unpacked-harvest", "version": 1, "rom": {"size": len(rom), "sha256": sha256(rom)},
            "image_changed": 0, "dropped": 0,
            "unpackers": [{"name": "tiles", "bank": 0, "address": UNPACK, "entered": len(things),
                           "returned": len(things), "not_in_reach": 0}],
            "made": [{"unpacker": "tiles", "bank": bank, "address": address, "times": 1, "sha256": sha256(made),
                      "bytes": made.hex()} for (bank, address), made in things]}


def save_state() -> bytes:
    """A save state with nothing in it, which is enough for `glyphs` to draw a sheet from."""
    header = gb_discover.HEADER.pack(gb_discover.SAVESTATE_MAGIC, 9, 0x1234, 0x8000, 0x2000, gb_discover.WRAM_SIZE,
                                     gb_discover.VRAM_SIZE, gb_discover.OAM_SIZE, gb_discover.HRAM_SIZE,
                                     gb_discover.IO_SIZE, 12, 0)
    return header + bytes(20 + 0x2000 + gb_discover.WRAM_SIZE + gb_discover.VRAM_SIZE + gb_discover.OAM_SIZE
                          + gb_discover.HRAM_SIZE + gb_discover.IO_SIZE + 12)


def run(command: list[str], expect: tuple[int, ...] = (0,), timeout: int = 300) -> subprocess.CompletedProcess:
    result = subprocess.run(command, capture_output=True, text=True, timeout=timeout)
    if result.returncode not in expect:
        raise AssertionError(f"exit {result.returncode} from {command!r}\n{result.stdout[-3000:]}\n"
                             f"{result.stderr[-3000:]}")
    return result


def tool(*arguments: object, expect: tuple[int, ...] = (0,)) -> subprocess.CompletedProcess:
    return run([sys.executable, str(GB_DATA), *map(str, arguments)], expect=expect)


def files_of(tree: Path) -> dict[str, bytes]:
    return {path.relative_to(tree).as_posix(): path.read_bytes() for path in sorted(tree.rglob("*"))
            if path.is_file()}


def manifest_of(tree: Path) -> dict:
    return json.loads((tree / "manifest.json").read_text(encoding="utf-8"))


def region_at(tree: Path, offset: int) -> dict:
    return next(region for region in manifest_of(tree)["regions"] if region["offset"] == offset)


def view_at(tree: Path, offset: int, kind: str = "tiles") -> dict:
    """The view of that kind that starts at a ROM offset, or a region's file of text."""
    for region in manifest_of(tree)["regions"]:
        for view in region.get("views", ()):
            if view["kind"] == kind and region["offset"] + view.get("offset", 0) == offset:
                return view
    raise AssertionError(f"no {kind} view at {offset:#x}")


def thing_of(tree: Path, stream: tuple[int, int], made: bytes) -> dict:
    return next(thing for thing in manifest_of(tree)["unpacked"]
                if (thing["bank"], thing["address"], thing["made_sha256"]) == (*stream, sha256(made)))


def names_by_themselves() -> None:
    """What a label is as a file name, and which label of several names a place."""
    stem = gb_data_names.file_stem
    assert stem("RedSprite") == "RedSprite" and stem("Routine.loop") == "Routine.loop"
    assert stem('a/b\\c:d*e?f"g<h>i|j') == "a_b_c_d_e_f_g_h_i_j" and stem("tab\there") == "tab_here"
    assert stem(".hidden") == "_hidden" and stem("dots...") == "dots" and stem("...") == "" and stem("") == ""
    assert len(stem("x" * 200)) == gb_data_names.LONGEST
    alone = gb_data_names.alone
    assert alone("Font", "Font") and alone("console", "console") and alone("Com10", "Com10")
    for device in ("con", "CON", "nul", "Aux", "prn", "com1", "LPT9", "con.tiles"):
        assert not alone(device, device), device
    for own in ("4180_unknown", "0000_code", "ABCD_pointer_table", "0B_4D7D", "0b_4d7d_2"):
        assert not alone(own, own), own
    assert alone("4180_Unknown", "4180_Unknown") and alone("0B_4D7D_x", "0B_4D7D_x") and alone("Face_X", "Face_X")
    assert not alone("x" * 81, "x" * 80) and alone("x" * 80, "x" * 80)
    every = {"Font", "FontEnd", "Legend", "Tiles", "Tiles_End", "Tiles.end", "Bend", "End"}
    assert [label for label in sorted(every) if gb_data_names.marks_end(label, every)] == \
        ["FontEnd", "Tiles.end", "Tiles_End"]
    assert gb_data_names.home(5, 0x4180) == (5, 0x4180) and gb_data_names.home(5, 0x0180) == (0, 0x0180)
    assert gb_data_names.home(0, 0xC100) is None


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--gbrecomp", required=True, type=Path)
    args = parser.parse_args()
    names_by_themselves()

    with tempfile.TemporaryDirectory(prefix="gbnames-") as scratch:
        root = Path(scratch)
        rom = make_rom()
        rom_path = root / "names.gb"
        rom_path.write_bytes(rom)
        export_path = root / "export.json"
        run([str(args.gbrecomp), str(rom_path), "--no-scan", "--pointer-scan", "off",
             *(word for address in CODE for word in ("--add-entry-point", f"{address // 0x4000}:{address:04X}")),
             "--lift-export", str(export_path)])
        symbols = root / "game.sym"
        symbols.write_text(SYMBOLS, encoding="utf-8")
        record_path, state_path = root / "use.json", root / "any.state"
        record_path.write_text(json.dumps(use_record(rom)), encoding="utf-8")
        state_path.write_bytes(save_state())
        first_harvest, second_harvest = root / "first.harvest.json", root / "second.harvest.json"
        first_harvest.write_text(json.dumps(harvest(rom, [
            (HERO, MADE[HERO]), (HERO, halves_changed(MADE[HERO])), (PACKED, MADE[PACKED]),
            (PLAIN, MADE[PLAIN]), (PLAIN, halves_changed(MADE[PLAIN]))])), encoding="utf-8")
        second_harvest.write_text(json.dumps(harvest(rom, [(LATE, MADE[LATE])])), encoding="utf-8")

        # A tree with everything in it: four pictures of tiles, a font, a file of text, six unpacked things.
        plain = root / "plain"
        tool("split", export_path, "--rom", rom_path, "-o", plain)
        data = [region for region in manifest_of(plain)["regions"] if region["kind"] == "data"]
        assert [region["offset"] for region in data] == [HOME, PACKS, ODDS, TILES, TWIN1, TWIN2, SEEN, LAST], data
        old = {region["offset"]: region["file"] for region in manifest_of(plain)["regions"]}
        stems = {offset: name[:-len(".bin")] for offset, name in old.items()}
        assert old[HOME] == "bank_00/0153_unknown.bin" and old[TILES] == "bank_01/4000_unknown.bin", old
        code_file = old[0x4800]
        assert code_file == "bank_01/4800_code.bin"

        def prepare(tree: Path) -> None:
            tool("tiles", tree, old[HOME], "--offset", FONT - HOME, "--tiles", 16, "--bpp", 1)
            tool("tiles", tree, old[HOME], "--offset", SPARE - HOME, "--tiles", 3)
            tool("tiles", tree, old[TILES], "--tiles", 16)
            tool("tiles", tree, old[TILES], "--offset", SPRITE - TILES, "--tiles", 8, "--width", 2)
            tool("tiles", tree, old[TILES], "--offset", BARE - TILES, "--tiles", 4)
            tool("uses", tree, record_path)
            (tree / "charmap.json").write_text(json.dumps(CHARMAP), encoding="utf-8")
            tool("text", tree)
            (tree / "unpackers.json").write_text(json.dumps(DECLARATION), encoding="utf-8")
            said = tool("unpacked", tree, first_harvest).stdout
            assert "5 new in" in said and "1 more was worked out" in said, said

        prepare(plain)
        text_plain = (plain / f"{stems[HOME]}.text.txt").read_text(encoding="utf-8")
        assert [line for line in text_plain.splitlines() if line.startswith("+")] == [
            "+002D 5 |FEED{end}|", "+01AD 20 |BAD CAFE{line}A FAB BEAD{end}|", "+01EE 9 |DEAF CAB{end}|"], text_plain
        named, late, clean = root / "named", root / "late", root / "clean"
        for tree in (named, late, clean):
            shutil.copytree(plain, tree)
        assert "names" not in manifest_of(plain) and not (plain / "names.sym").exists()

        def built(tree: Path, *more: str, expect: tuple[int, ...] = (0,)) -> tuple[bytes, bytes, str]:
            """The image and the pack a tree builds, and what `build` said."""
            image = root / "built" / f"{tree.name}.gb"
            said = tool("build", tree, "-o", image, *more, expect=expect).stdout
            return image.read_bytes(), image.with_suffix(".gbup").read_bytes(), said

        def original(tree: Path) -> None:
            image, pack, said = built(tree, "--expect-original")
            assert image == bytes(rom) and "the original ROM, byte for byte" in said, said
            assert pack == built(plain)[1] and "0 replacements" in said, said
            assert "nothing edited" in tool("status", tree).stdout

        original(plain)

        # ---- Named from a symbol file somebody brought.
        said = tool("names", named, "--sym", symbols, "--list", root / "list.txt").stdout
        assert "game.sym: 12 addresses of what the tree has named from it; 4 of its labels are inside code or " \
            "not in this ROM" in said, said
        assert "names.sym: 12 addresses have a name, 0 written by hand and 12 brought in" in said, said
        assert "regions   3 of 8 files of data are called by a name" in said, said
        assert "1 of them hold other names as well, and say how many: Label_and_N_more" in said, said
        assert "views     4 of 6 pictures and files of text are called by a name" in said, said
        assert "strings   1 of 3 start at a name, and 1 more after one in their region (Label+N)" in said, said
        assert "unpacked  4 of 6 things are called by a name, of 2 of 3 streams" in said, said
        assert "3 data files have more than one name in them" in said and "15 files renamed" in said, said
        names_file = named / "names.sym"
        written = names_file.read_text(encoding="utf-8")
        assert written == gb_data_names.HEAD + BROUGHT_IN, written

        def expected_files(tree: Path, renamed: dict[str, str], gone: tuple[str, ...] = (),
                           more: tuple[str, ...] = ()) -> None:
            """The tree's files are the unnamed tree's with these called something else."""
            want = sorted([renamed.get(name, name) for name in files_of(plain) if name not in gone]
                          + ["names.sym", *more])
            assert sorted(files_of(tree)) == want, sorted(set(files_of(tree)) ^ set(want))

        twin1, twin2 = stems[TWIN1].split("/")[1], stems[TWIN2].split("/")[1]
        by_name = {
            f"{stems[TILES]}.bin": "bank_01/Tiles_and_3_more.bin",
            f"{stems[TILES]}.tiles.png": "bank_01/Tiles.tiles.png",
            f"{stems[TILES]}.tiles_4100.png": "bank_01/Sprite.tiles.png",
            f"{stems[TILES]}.tiles_4200.png": "bank_01/Tiles_and_3_more.tiles_4200.png",
            f"{stems[HOME]}.tiles_0200.png": "bank_00/Font.tiles.png",
            # Two labels that differ only in capitals are one file name where capitals do not count.
            f"{stems[TWIN1]}.bin": f"bank_01/Twin.{twin1}.bin",
            f"{stems[TWIN2]}.bin": f"bank_01/TWIN.{twin2}.bin",
            "unpacked/tiles/01_2100.made": "unpacked/tiles/Hero.made",
            "unpacked/tiles/01_2100.png": "unpacked/tiles/Hero.png",
            "unpacked/tiles/01_2100_2.made": "unpacked/tiles/Hero_2.made",
            "unpacked/tiles/01_2100_2.png": "unpacked/tiles/Hero_2.png",
            "unpacked/tiles/01_4801.made": "unpacked/tiles/Packed.made",
            "unpacked/tiles/01_4801.png": "unpacked/tiles/Packed.png",
            "unpacked/tiles/01_4801_2.made": "unpacked/tiles/Packed_2.made",
            "unpacked/tiles/01_4801_2.png": "unpacked/tiles/Packed_2.png"}
        assert all(name in files_of(plain) for name in by_name), sorted(files_of(plain))
        expected_files(named, by_name)
        # Nothing in a file changed but the comments in the file of text.
        before, after = files_of(plain), files_of(named)
        text_name = f"{stems[HOME]}.text.txt"
        for name, content in before.items():
            if name not in ("manifest.json", text_name):
                assert after[by_name.get(name, name)] == content, name
        text_named = after[text_name].decode("utf-8")
        assert text_named == text_plain.replace("+01AD 20", "# 00:0300 Greeting\n+01AD 20").replace(
            "+01EE 9", "# 00:0341 Shout+1\n+01EE 9"), text_named
        # The manifest follows: the files, each region's names, and what every renamed file was called.
        manifest = manifest_of(named)
        assert region_at(named, TILES)["file"] == "bank_01/Tiles_and_3_more.bin"
        assert [view["file"] for view in region_at(named, TILES)["views"]] == [
            "bank_01/Tiles.tiles.png", "bank_01/Sprite.tiles.png", "bank_01/Tiles_and_3_more.tiles_4200.png"]
        assert [view["file"] for view in region_at(named, HOME)["views"]] == [
            text_name, "bank_00/Font.tiles.png", f"{stems[HOME]}.tiles_0400.png"]
        assert manifest["names"] == {"was": {new: before_name for before_name, new in sorted(
            by_name.items(), key=lambda item: item[1]) if before_name.endswith((".bin", ".made"))}}, manifest["names"]
        labels = {region["offset"]: region["labels"] for region in manifest["regions"] if "labels" in region}
        assert labels == {HOME: [[FONT - HOME, "Font"], [STRING1 - HOME, "Greeting"], [SHOUT - HOME, "Shout"]],
                          PACKS: [[HERO[1] - PACKS, "Hero"], [LATE[1] - PACKS, "Late"]],
                          TILES: [[0, "Tiles"], [SPRITE - TILES, "Sprite"], [WALK - TILES, "Walk"],
                                  [MUGSHOT - TILES, "Mugshot"]],
                          0x4800: [[1, "Packed"]],
                          TWIN1: [[0, "Twin"]], TWIN2: [[0, "TWIN"]]}, labels
        assert thing_of(named, HERO, MADE[HERO])["file"] == "unpacked/tiles/Hero.png"
        assert thing_of(named, PACKED, halves_changed(MADE[PACKED]))["made"] == "unpacked/tiles/Packed_2.made"
        assert view_at(named, HOME, "text")["sha256"] == sha256(after[text_name])    # as written, not an edit
        listing = (root / "list.txt").read_text(encoding="utf-8")
        for line in ("01:4000 data Tiles bank_01/Tiles_and_3_more.bin (2048 bytes)", "  01:4100 tiles Sprite bank_01/Sprite.tiles.png",
                     "  01:4300 label Mugshot +0300", "    00:0300 string Greeting +01AD (20 bytes)",
                     f"00:0153 data - {old[HOME]} (7853 bytes)", f"01:4800 code - {code_file} (3 bytes)",
                     "01:2100 unpacked by tiles: unpacked/tiles/Hero_2.png"):
            assert line in listing.splitlines(), (line, listing)

        # Named, the tree is still the ROM, and it is so with its charmap gone: nothing is read as edited.
        original(named)
        (named / "charmap.json").rename(named / "charmap.away")
        original(named)
        (named / "charmap.away").rename(named / "charmap.json")

        # Naming twice changes nothing, and the symbol file brought in again adds nothing.
        once = files_of(named)
        said = tool("names", named).stdout
        assert "0 files renamed" in said and "game.sym" not in said, said
