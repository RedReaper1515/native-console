#!/usr/bin/env python3
"""The files of a data tree called by name, and nothing lost by it.

Builds a small ROM of eight data regions in two banks, with a font, tiles,
three strings and four packed streams in them. No game is compiled: what a
game would have recorded (`--data-use`) and harvested (`--unpacked-harvest`)
is written out by the test, and so is a save state. A tree is made of it
with pictures, a file of text and unpacked things, and copied, so that one
copy is named and one never is. Then:

- `gb_data.py names --sym` has to bring in the labels of a symbol file that
  lie on what the tree has, and no others, and call every file by its name:
  a region, a view by its own name or its region's, the ways a stream was
  unpacked. The manifest has to follow, list each region's names, and keep
  what every file was called. A string's name goes over its line;
- named, the tree still builds to the original ROM, and with edits made
  before the naming, or after it, to the image and the pack the unnamed
  tree builds with the same edits;
- naming twice changes nothing, and bringing the symbol file in again adds
  nothing;
- `tiles`, `text`, `unpacked`, `uses`, `annotations`, `glyphs`, `status` and
  `build` go on working: a picture drawn again keeps its name, a picture or
  an unpacked thing made afterwards takes its name, and a file can still be
  asked for by its address;
- a line somebody wrote wins over the symbol file's and stays through a
  second bringing in, as does a line changed in place;
- a data file that holds other names than its own says how many in its
  name (`Label_and_N_more`), by the count the manifest lists; a view keeps
  the name of where it starts; and a tree named when such a file went by
  its first name alone is brought to this by the next run;
- two labels that would make one file name, a device's name, a label that
  looks like one of the tool's own names, one too long and one with
  characters no file name takes all get a name that can be told apart;
- a file that is in the way is not written over, a renaming that fails half
  way is taken back, and one that was cut short is taken back by the next
  command;
- `--seen` calls a file that has no name by what the game used most of it
  as, and a name somebody gave wins over that;
- with a name taken away its file has its old name back, and with all of
  them taken away the tree is the unnamed tree again, file for file and
  byte for byte, manifest included.
"""
