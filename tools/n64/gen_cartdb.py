#!/usr/bin/env python3
"""Write runtimes/runtime-n64/src/n64_cartdb.c from ares's Nintendo 64 save database.

The save hardware of an N64 cartridge (EEPROM 4/16 Kbit, SRAM, FlashRAM) and
the accessories a game supports are not in its header. ares
(mia/medium/nintendo-64.cpp, ISC) keeps a table keyed by the game code; this
script turns its one-line entries into a C table. The handful of entries that
depend on the region or the revision are written by hand in n64_cartdb.c's
template below, from the same source.

    python3 tools/n64/gen_cartdb.py PATH/TO/ares/mia/medium/nintendo-64.cpp
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "runtimes" / "runtime-n64" / "src" / "n64_cartdb.c"

LINE = re.compile(r'^\s*if\(id == "(\w{3})"\)\s*\{([^}]*)\}')


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    src = Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")
    rows = {}
    for line in src.splitlines():
        m = LINE.match(line)
        if not m:
            continue
        gid, body = m.group(1), m.group(2)
        eeprom = sram = 0
        flash = cpak = rpak = tpak = rtc = 0
        model = 0
        for part in body.split(";"):
            part = part.strip()
            if part.startswith("eeprom"):
                eeprom = 16 if "2_KiB" in part else 4
            elif part.startswith("sram"):
                sram = {"32_KiB": 32, "96_KiB": 96, "128_KiB": 128}.get(part.split("=")[1].strip(), 32)
            elif part.startswith("flash ="):
                flash = 1
            elif part.startswith("flashModel"):
                model = 0 if "MX29L1100" in part else 1
            elif part.startswith("cpak"):
                cpak = 1
            elif part.startswith("rpak"):
                rpak = 1
            elif part.startswith("tpak"):
                tpak = 1
            elif part.startswith("rtc"):
                rtc = 1
        rows[gid] = (eeprom, sram, flash, model, cpak, rpak, tpak, rtc)
    out = []
    out.append("/*\n * Save hardware and accessories by game code. Generated by\n"
               " * tools/n64/gen_cartdb.py from ares (mia/medium/nintendo-64.cpp, commit\n"
               " * 9408cb43d4948fc3ea6e152a307a34348df3fe04). Do not edit the table by hand.\n"
               " *\n * Copyright (c) 2004-2025 ares team, Near et al. Permission to use, copy,\n"
               " * modify, and/or distribute this software for any purpose with or without\n"
               " * fee is hereby granted, provided that the above copyright notice and this\n"
               " * permission notice appear in all copies.\n */\n")
    out.append('#include <stdlib.h>\n#include <string.h>\n\n#include "n64.h"\n\n')
    out.append("typedef struct {\n    char id[4];\n    uint8_t eeprom_kbit, sram_kib, flash, flash_model, cpak, rpak, tpak, rtc;\n} CartRow;\n\n")
    out.append("static const CartRow rows[] = {\n")
    for gid in sorted(rows):
        e, s, f, mo, c, r, t, rt = rows[gid]
        out.append('    { "%s", %d, %d, %d, %d, %d, %d, %d, %d },\n' % (gid, e, s, f, mo, c, r, t, rt))
    out.append("};\n\n")
    out.append(r'''static int compare(const void *key, const void *row) { return memcmp(key, ((const CartRow *)row)->id, 3); }

void n64_cartdb_lookup(N64Cart *cart)
{
    char id[3] = { cart->id[0], cart->id[1], cart->id[2] };
    const char region = cart->id[3];
    const CartRow *row = bsearch(id, rows, sizeof rows / sizeof rows[0], sizeof rows[0], compare);
    if (row) {
        cart->eeprom_kbit = row->eeprom_kbit;
        cart->sram_size = (uint32_t)row->sram_kib * 1024u;
        cart->flash = row->flash != 0;
        cart->flash_model = row->flash_model;
        cart->cpak = row->cpak != 0;
        cart->rpak = row->rpak != 0;
        cart->rtc = row->rtc != 0;
    }
    /* The entries that depend on the region or the revision. */
    if (!memcmp(id, "NSM", 3)) cart->eeprom_kbit = 4;
    if (!memcmp(id, "NWR", 3)) {
        cart->eeprom_kbit = 4;
        cart->cpak = true;
    }
    if (!memcmp(id, "NK4", 3)) {
        if (region == 'J' && cart->revision < 2) {
            cart->sram_size = 0x8000u;
            cart->eeprom_kbit = 0;
        } else {
            cart->eeprom_kbit = 16;
        }
        cart->rpak = true;
    }
    if (!memcmp(id, "NDK", 3) && region == 'J') cart->eeprom_kbit = 4;
    if (!memcmp(id, "NWT", 3)) {
        if (region == 'J') cart->eeprom_kbit = 4;
        else cart->cpak = true;
    }
    if (!memcmp(id, "ND3", 3) || !memcmp(id, "ND4", 3)) {
        if (region == 'J') {
            cart->eeprom_kbit = 16;
            cart->rpak = true;
        } else {
            cart->cpak = true;
        }
    }
    /* Homebrew: the "ED" game code with the save type in byte 0x3F. */
    if (cart->id[1] == 'E' && cart->id[2] == 'D') {
        switch (cart->revision >> 4) {
        case 1: cart->eeprom_kbit = 4; break;
        case 2: cart->eeprom_kbit = 16; break;
        case 3: cart->sram_size = 0x8000u; break;
        case 4: cart->sram_size = 0x18000u; break;
        case 5: cart->flash = true; cart->flash_model = 1; break;
        case 6: cart->sram_size = 0x20000u; break;
        default: break;
        }
        if (cart->revision & 1u) cart->rtc = true;
    }
}
''')
    OUT.write_text("".join(out), newline="\n")
    print("wrote %d games to %s" % (len(rows), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
