#!/usr/bin/env python3
"""Turn a measurement of fres and frsqrte into the tables they look up.

`fres` and `frsqrte` do not compute a result; they read a piecewise-linear
table. The manual declines to print it - "the value placed into register frD
may vary between implementations" - so tests/gc/vectors/gen/gc_estimate_gen.c
measures it on an oracle and this fits the pieces.

    python tools/gc/build_gc_programs.py --source tests/gc/vectors/gen         --program gc_estimate_gen --out build/gc-vectors
    python tools/gc/capture_vectors.py --elf ... # run it, keep the log
    python tools/gc/fit_estimate_tables.py measurement.txt

The model, recovered from the measurement rather than assumed:

    segment  = mantissa >> 47                       (32 of them)
    i        = (mantissa & ((1 << 47) - 1)) >> 37    (10 bits)
    mantissa of the result, as a single = base[segment] - ((dec[segment] * i + 3) >> 2)

`frsqrte` has two tables, one for each parity of the operand's exponent,
because halving the exponent is part of what it does.

Every measured point has to come back exactly out of the fitted table, or
this fails: an estimate that is nearly right is a bug that shows up as a
game's physics drifting, not as a crash.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_OUT = REPO_ROOT / "runtime-gc" / "include" / "gc_estimate_tables.h"

MANTISSA = (1 << 52) - 1
SEGMENT_SHIFT = 47
INDEX_SHIFT = 37
# The rounding the hardware applies to the interpolation. It is not the same
# for both instructions, so it is searched for rather than assumed, and the
# answer is written into the generated header.
ROUNDINGS = [(add, shift) for shift in (1, 2, 3, 4) for add in range(0, 1 << shift)]


def read_measurement(path: Path) -> dict[str, list[tuple[int, int]]]:
    rows: dict[str, list[tuple[int, int]]] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        parts = line.replace("V|", "").split()
        if len(parts) != 3:
            continue
        try:
            rows.setdefault(parts[0], []).append((int(parts[1], 16), int(parts[2], 16)))
        except ValueError:
            continue
    return rows


def fit_with(segments, add, shift):
    """segment -> (base, dec) for one rounding, or None if it does not fit."""
    table: dict[int, tuple[int, int]] = {}
    for segment, samples in sorted(segments.items()):
        (low0, out0), (low1, out1) = samples[0], samples[-1]
        i0, i1 = low0 >> INDEX_SHIFT, low1 >> INDEX_SHIFT
        if i1 == i0:
            return None
        guess = round((out0 - out1) * (1 << shift) / (i1 - i0))
        hit = None
        for dec in range(max(0, guess - 64), guess + 65):
            base = out0 + ((dec * i0 + add) >> shift)
            if all(out == base - ((dec * (low >> INDEX_SHIFT) + add) >> shift)
                   for low, out in samples):
                hit = (base, dec)
                break
        if hit is None:
            return None
        table[segment] = hit
    return table if len(table) == 32 else None


def fit(points: list[tuple[int, int]]):
    """(segment -> (base, dec), round_add, round_shift), exact everywhere."""
    segments: dict[int, list[tuple[int, int]]] = {}
    for value, result in points:
        mantissa = value & MANTISSA
        segments.setdefault(mantissa >> SEGMENT_SHIFT, []).append(
            (mantissa & ((1 << SEGMENT_SHIFT) - 1), (result & MANTISSA) >> 29)
        )
    for samples in segments.values():
        samples.sort()

    for add, shift in ROUNDINGS:
        table = fit_with(segments, add, shift)
        if table:
            return table, add, shift
    raise RuntimeError("no rounding in the searched set reproduces every measured point")


def emit(tables: dict[str, dict[int, tuple[int, int]]]) -> str:
    out: list[str] = []
    w = out.append
    w("/* Generated by tools/gc/fit_estimate_tables.py from a measurement made by")
    w(" * tests/gc/vectors/gen/gc_estimate_gen.c. Do not edit.")
    w(" *")
    w(" * fres and frsqrte look their results up rather than computing them, and")
    w(" * the manual does not print the table. These numbers are measured, and")
    w(" * every measured point comes back out of them exactly.")
    w(" *")
    w(" * The result's mantissa, as a single:")
    w(" *   segment = mantissa >> 47")
    w(" *   i       = (mantissa & ((1 << 47) - 1)) >> 37")
    w(" *   result  = base[segment] - ((dec[segment] * i + 3) >> 2)")
    w(" *")
    w(" * frsqrte has one table per parity of the operand's exponent, because")
    w(" * halving that exponent is part of the operation.")
    w(" */")
    w("#ifndef GC_ESTIMATE_TABLES_H")
    w("#define GC_ESTIMATE_TABLES_H")
    w("")
    w("#include <stdint.h>")
    w("")
    w("typedef struct GcEstimateEntry {")
    w("  uint32_t base;")
    w("  uint32_t dec;")
    w("} GcEstimateEntry;")
    w("")
    w("#define GC_ESTIMATE_SEGMENT_SHIFT 47")
    w("#define GC_ESTIMATE_INDEX_SHIFT 37")
    w("")
    w("typedef struct GcEstimateTable {")
    w("  GcEstimateEntry entries[32];")
    w("  uint32_t round_add;   /* the interpolation's rounding, measured too */")
    w("  uint32_t round_shift;")
    w("} GcEstimateTable;")
    w("")
    for name, (table, add, shift) in tables.items():
        w(f"static const GcEstimateTable {name} = {{")
        w("    {")
        for segment in range(32):
            base, dec = table[segment]
            w(f"        {{{base:#09x}u, {dec:5d}u}},")
        w("    },")
        w(f"    {add}u, {shift}u,")
        w("};")
        w("")
    w("#endif /* GC_ESTIMATE_TABLES_H */")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("measurement", type=Path)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    rows = read_measurement(args.measurement)
    wanted = {
        "gc_fres_table": "fres",
        "gc_frsqrte_table_odd_exponent": "frsqrte_even",
        "gc_frsqrte_table_even_exponent": "frsqrte_odd",
    }
    tables = {}
    for name, key in wanted.items():
        if key not in rows:
            print(f"fit_estimate_tables: the measurement has no {key} sweep", file=sys.stderr)
            return 1
        try:
            table, add, shift = fit(rows[key])
        except RuntimeError as error:
            print(f"fit_estimate_tables: {key}: {error}", file=sys.stderr)
            return 1
        tables[name] = (table, add, shift)
        print(f"{key}: 32 segments from {len(rows[key])} points, "
              f"rounding (x + {add}) >> {shift}")

    args.out.write_text(emit(tables), encoding="utf-8", newline="\n")
    print(f"fit_estimate_tables: -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
