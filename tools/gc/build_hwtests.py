#!/usr/bin/env python3
"""Build the hardware test suite into runnable GameCube ELFs.

dolphin-emu/hwtests is GPL-2.0. It is fetched by tools/fetch_gc_tests.py,
built here and run as a tool; its code is never copied into this repository
and the binaries are never redistributed (docs/GC-PLAN.md, "What we reuse").

The suite is written for a Wii: it passes -mrvl, links against
libogc/lib/wii, and pulls in wiiuse and bte. The `cputest` programs
themselves are pure CPU and say nothing Wii-specific, but the start-up
around them is the Wii's, so this builds from a *copy* with three edits
applied that point it at a GameCube. The copy is what keeps roms/gc
matching its manifest, and the edits fail closed: if an upstream change
means a pattern is no longer there, the build stops rather than quietly
producing Wii executables again.

It needs devkitPPC, which is not a dependency of anything this project
ships: the vectors it helps produce are checked in, and CI runs against
those. Without DEVKITPRO set this exits non-zero and says what is missing,
rather than quietly building nothing.

    python tools/gc/build_hwtests.py
    python tools/gc/build_hwtests.py --source roms/gc/hwtests --build build/hwtests

The result is an ELF per test under the build directory. Run one with
`gc_run`, which hooks the weak OSReport symbol the suite reports its
verdicts through.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent


# The suite reports its verdicts over a TCP socket to a listening host, and
# its main calls the Wii remote's initialiser. A GameCube has neither: the
# network calls live in the Wii build of libogc, and there is no Wii remote.
# Neither matters here, because the verdicts arrive through the weak
# OSReport symbol the suite also calls - which is exactly the path its own
# source says is "for Dolphin's benefit". These stubs let it link.
GC_STUBS = """/* Generated by tools/gc/build_hwtests.py. Not part of the suite. */
#include <stdint.h>

typedef int32_t s32;
typedef uint32_t u32;

/* net_bind has to succeed: the suite loops until it does. net_accept would
 * block on hardware until a host connected; here it returns at once. */
s32 net_init(void) { return 0; }
s32 net_socket(u32 domain, u32 type, u32 protocol) { (void)domain; (void)type; (void)protocol; return 3; }
s32 net_setsockopt(s32 s, u32 level, u32 name, const void *value, u32 length) {
  (void)s; (void)level; (void)name; (void)value; (void)length; return 0;
}
s32 net_bind(s32 s, void *name, u32 length) { (void)s; (void)name; (void)length; return 0; }
s32 net_listen(s32 s, u32 backlog) { (void)s; (void)backlog; return 0; }
s32 net_accept(s32 s, void *address, u32 *length) { (void)s; (void)address; (void)length; return 4; }
s32 net_send(s32 s, const void *data, s32 size, u32 flags) {
  (void)s; (void)data; (void)flags; return size;
}
s32 net_close(s32 s) { (void)s; return 0; }

/* No buttons are ever down: the one test that reads them uses HOME as an
 * escape hatch out of a long sweep, and a headless run wants the whole
 * sweep. */
s32 WPAD_Init(void) { return 0; }
s32 WPAD_ScanPads(void) { return 0; }
u32 WPAD_ButtonsDown(s32 channel) { (void)channel; return 0; }
"""


def fail(message: str) -> int:
    print(f"build_hwtests: {message}", file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=REPO_ROOT / "roms" / "gc" / "hwtests")
    parser.add_argument("--work", type=Path, default=REPO_ROOT / "build" / "hwtests-gc")
    parser.add_argument("--build", type=Path, default=REPO_ROOT / "build" / "hwtests")
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 1)
    parser.add_argument(
        "--wii", action="store_true",
        help="build the suite for the console it was written for, the Wii, into "
             "build/wii-hwtests. Its network reporting and its Wii Remote calls are still "
             "replaced: the verdicts come out through OSReport either way, and a headless "
             "machine has no host to connect to. (iostest measures IOS's timings rather than "
             "judging them, and does not compile against a current libogc; it stays out.)")
    parser.add_argument(
        "--modules", default="cputest,gxtest",
        help="which of the suite's modules to build. iostest is left out by default: it tests "
             "the Wii's IOS, which a GameCube does not have, and it does not compile against a "
             "current libogc.")
    args = parser.parse_args()
    if args.wii:
        # The Wii's own places, unless others were named.
        if args.work == REPO_ROOT / "build" / "hwtests-gc":
            args.work = REPO_ROOT / "build" / "hwtests-wii"
        if args.build == REPO_ROOT / "build" / "hwtests":
            args.build = REPO_ROOT / "build" / "wii-hwtests"

    if not (args.source / "CMakeLists.txt").exists():
        return fail(f"{args.source} has no CMakeLists.txt; run tools/fetch_gc_tests.py first")

    devkitpro = os.environ.get("DEVKITPRO")
    devkitppc = os.environ.get("DEVKITPPC")
    if not devkitpro or not devkitppc:
        return fail(
            "DEVKITPRO and DEVKITPPC must be set. hwtests is a GameCube program and needs "
            "devkitPPC to build; see https://devkitpro.org/wiki/Getting_Started"
        )
    if not Path(devkitppc, "bin").is_dir():
        return fail(f"DEVKITPPC={devkitppc} has no bin directory")

    if not (args.source / "toolchain-powerpc.cmake").exists():
        return fail(f"{args.source / 'toolchain-powerpc.cmake'} is missing")

    cmake = shutil.which("cmake")
    if not cmake:
        return fail("cmake is not on PATH")

    # Build from a copy with the Wii turned into a GameCube.
    if args.work.exists():
        shutil.rmtree(args.work)
    shutil.copytree(args.source, args.work)
    lists = args.work / "CMakeLists.txt"
    text = lists.read_text(encoding="utf-8")
    edits = [
        ("link_directories(${DEVKITPRO}/libogc/lib/wii)",
         "link_directories(${DEVKITPRO}/libogc/lib/cube)"),
        ('set(MACHDEP "-DGEKKO -mrvl -mcpu=750 -meabi -mhard-float")',
         'set(MACHDEP "-DGEKKO -mogc -mcpu=750 -meabi -mhard-float")'),
    ]
    if args.wii:
        # A Wii program as written; only the two libraries the stubs stand
        # in for are left out. The Wii's libogc has network functions of
        # its own, which the stubs would collide with at link time, so the
        # suite's calls and the stubs are both renamed out of their way.
        names = ["net_init", "net_socket", "net_setsockopt", "net_bind", "net_listen", "net_accept",
                 "net_send", "net_close"]
        renames = " ".join(f"{name}=hwtests_{name}" for name in names)
        edits = [
            ("set(CMAKE_CXX_STANDARD 17)",
             f"add_compile_definitions({renames})\nset(CMAKE_CXX_STANDARD 17)"),
        ]
    edits += [
        ("target_link_libraries(${executable_name} hwtests_common fmt::fmt wiiuse bte fat ogc m)",
         "target_link_libraries(${executable_name} hwtests_common fmt::fmt fat ogc m)"),
    ]
    edits += [
        ("project(hwtests CXX ASM)", "project(hwtests C CXX ASM)"),
        ("add_executable(${executable_name} ${add_hwtest_FILES})",
         "add_executable(${executable_name} ${add_hwtest_FILES} ${CMAKE_SOURCE_DIR}/gc_stubs.c)"),
    ]
    (args.work / "gc_stubs.c").write_text(GC_STUBS, encoding="utf-8")
    for old, new in edits:
        if old not in text:
            return fail(
                f"the suite's CMakeLists no longer contains {old!r}; it has changed upstream and "
                "the GameCube retarget has to be looked at again rather than assumed"
            )
        text = text.replace(old, new)
    lists.write_text(text, encoding="utf-8", newline="\n")
    toolchain = args.work / "toolchain-powerpc.cmake"

    args.build.mkdir(parents=True, exist_ok=True)
    configure = [
        cmake,
        "-S", args.work.as_posix(),
        "-B", args.build.as_posix(),
        # Forward slashes: CMake reads a backslash in a -D value as an escape,
        # and a Windows path quietly turns into a toolchain file it cannot
        # find - leaving it to configure with the host compiler instead.
        f"-DCMAKE_TOOLCHAIN_FILE={toolchain.as_posix()}",
        "-DCMAKE_BUILD_TYPE=Release",
        "-G", "Ninja",
    ]
    libogc = Path(devkitpro, "libogc")
    if libogc.is_dir():
        configure.append(f"-DLIBOGCDIR={libogc.as_posix()}")

    if not (args.source / "Externals" / "fmt" / "CMakeLists.txt").exists():
        return fail(
            f"{args.source / 'Externals' / 'fmt'} is missing. hwtests keeps fmt as a submodule, "
            "which a source tarball does not carry; tools/fetch_gc_tests.py fetches it as its "
            "own pinned suite."
        )

    # Only the modules asked for: the suite builds for a Wii and its
    # iostest module is about hardware a GameCube does not have.
    targets = []
    for module in args.modules.split(","):
        module = module.strip()
        if not module:
            continue
        lists = args.work / module / "CMakeLists.txt"
        if not lists.exists():
            return fail(f"{lists} does not exist")
        for line in lists.read_text(encoding="utf-8").splitlines():
            match = re.search(r"TEST\s+(\w+)", line)
            if match and "add_hwtest" in line:
                targets.append(f"{module}_{match.group(1)}")
    if not targets:
        return fail(f"no tests found in {args.modules}")

    build = [cmake, "--build", args.build.as_posix(), "-j", str(args.jobs), "--target", *targets]
    for command in (configure, build):
        print(" ".join(command), flush=True)
        result = subprocess.run(command)
        if result.returncode != 0:
            return fail(f"command failed with {result.returncode}")

    elves = sorted(args.build.rglob("*.elf"))
    if not elves:
        return fail("the build produced no ELF files")
    print(f"build_hwtests: {len(elves)} test programs in {args.build}")
    for elf in elves:
        print(f"  {elf.relative_to(args.build)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
