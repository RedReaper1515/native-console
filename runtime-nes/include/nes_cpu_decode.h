static inline const NesOpInfo *nes_opinfo(uint8_t opcode)
{
#define NES_OPINFO_ENTRY(op, mn, am, fl, fg) { mn, (uint8_t)(am), (uint8_t)(fl), (uint8_t)(fg) },
    static const NesOpInfo table[256] = { NES_OPINFO_TABLE(NES_OPINFO_ENTRY) };
#undef NES_OPINFO_ENTRY
    return &table[opcode];
}

/* Bytes in the instruction, opcode included. BRK counts 2: the return
 * address it pushes skips the byte after the opcode. */
static inline unsigned nes_insn_length(uint8_t opcode)
{
    switch ((NesAddrMode)nes_opinfo(opcode)->mode) {
    case NES_AM_IMP: case NES_AM_ACC: return 1;
    case NES_AM_ABS: case NES_AM_ABSX: case NES_AM_ABSY: case NES_AM_IND: return 3;
    default: return 2;
    }
}

static inline bool nes_op_official(uint8_t opcode) { return (nes_opinfo(opcode)->flags & NES_OPF_OFFICIAL) != 0; }

/* The instruction writes through its operand's address (see NES_OPF_WRITES). */
static inline bool nes_op_writes(uint8_t opcode) { return (nes_opinfo(opcode)->flags & NES_OPF_WRITES) != 0; }

/* That write can land outside page 0, so in I/O or cartridge space: every
 * writing opcode except the zero-page forms, whose address is always
 * $0000-$00FF. */
static inline bool nes_op_writes_beyond_zp(uint8_t opcode)
{
    const NesOpInfo *info = nes_opinfo(opcode);
    return (info->flags & NES_OPF_WRITES) != 0 && info->mode != NES_AM_ZP && info->mode != NES_AM_ZPX &&
           info->mode != NES_AM_ZPY;
}

